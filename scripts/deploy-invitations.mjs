import { readFile, writeFile } from 'node:fs/promises';
import { createInterface } from 'node:readline/promises';
import { ContractFactory, JsonRpcProvider, Wallet, keccak256, formatEther } from 'ethers';
import { compileInvitations } from './compile-invitations.mjs';
import { matchesRuntime } from './prepare-booking-deployment.mjs';

const configPath = new URL('../decent-calendar-vanilla/decent.config.js', import.meta.url);
const source = await readFile(configPath, 'utf8');
const config = Function(`${source.replace('window.DECENT_CONFIG =', 'return')} `)();
if (config.invitations?.address) throw new Error('Invitation registry is already pinned. Refusing a duplicate deployment.');
const provider = new JsonRpcProvider(process.env.DCAL_DEPLOY_RPC || 'https://mainnet.base.org');
if ((await provider.getNetwork()).chainId !== 8453n) throw new Error('Deployment RPC is not Base.');
const booking = config.booking.address;
if (keccak256(await provider.getCode(booking)) !== config.booking.runtimeCodeHash) throw new Error('Booking runtime mismatch.');
const compiled = await compileInvitations();
await writeFile(new URL('../docs/deployments/base-dcal-invitations-1.standard-input.json', import.meta.url), JSON.stringify(compiled.input, null, 2) + '\n');
const key = process.env.DEPLOYER_PRIVATE_KEY?.trim();
if (!key) throw new Error('Set DEPLOYER_PRIVATE_KEY in the existing gitignored .env. Never paste it in chat.');
const wallet = new Wallet(key, provider);
if (wallet.address.toLowerCase() !== config.booking.feeRecipient.toLowerCase()) throw new Error('Use the approved DecentAgency.eth deployer.');
const factory = new ContractFactory(compiled.artifact.abi, compiled.artifact.evm.bytecode.object, wallet);
const unsigned = await factory.getDeployTransaction(booking);
const gas = await provider.estimateGas({ ...unsigned, from: wallet.address }), fees = await provider.getFeeData();
console.log({ chain: 8453, deployer: wallet.address, booking, gas: gas.toString(), maxEstimateETH: formatEther(gas * (fees.maxFeePerGas || fees.gasPrice)), balanceETH: formatEther(await provider.getBalance(wallet.address)) });
const prompt = createInterface({ input: process.stdin, output: process.stdout });
const answer = await prompt.question('Deploy public invitations (no funds, NO seat enforcement)? Type DEPLOY: ');
prompt.close();
if (answer !== 'DEPLOY') throw new Error('Deployment cancelled.');
const contract = await factory.deploy(booking);
console.log('Deployment submitted:', contract.deploymentTransaction().hash);
const receipt = await contract.deploymentTransaction().wait(2);
const address = await contract.getAddress(), code = await provider.getCode(address);
if (!matchesRuntime(code, compiled.artifact) || await contract.VERSION() !== 'dcal-invitations-1' || (await contract.booking()).toLowerCase() !== booking.toLowerCase()) throw new Error('Post-deployment verification failed.');
const runtimeCodeHash = keccak256(code);
const record = { chainId: 8453, address, booking, deployer: wallet.address, transactionHash: receipt.hash, blockNumber: receipt.blockNumber, runtimeCodeHash, compiler: compiled.compiler, version: 'dcal-invitations-1' };
await writeFile(new URL('../docs/deployments/base-dcal-invitations-1.json', import.meta.url), JSON.stringify(record, null, 2) + '\n');
if (!/invitations: \{ address: '', runtimeCodeHash: '' \}/.test(source)) throw new Error('Config changed: pin deployment manually using the saved record.');
await writeFile(configPath, source.replace("invitations: { address: '', runtimeCodeHash: '' }", `invitations: { address: '${address}', runtimeCodeHash: '${runtimeCodeHash}' }`));
console.log('Deployed, runtime checked and config pinned:', record);
provider.destroy();
